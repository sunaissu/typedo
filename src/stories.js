export function storyRoute(story, route) {
  if (!story?.choice) return undefined;
  const selected = route === undefined ? story.choice.defaultRoute : route;
  return story.choice.routes.some(item => item.id === selected) ? selected : undefined;
}

export function getStoryChapter(story, chapterIndex, route) {
  const chapter = story?.chapters[chapterIndex];
  if (story?.choice?.chapterIndex !== chapterIndex) return chapter;
  return story.choice.routes.find(item => item.id === storyRoute(story, route))?.chapter || chapter;
}

export function storyWordCount(story, route) {
  return story.chapters.reduce((total, _chapter, index) => total + getStoryChapter(story, index, route).text.split(' ').length, 0);
}

export function filterStories({ query = '', genre = '', length = '', completion = '', difficulty = '' } = {}, progress = {}, drafts = {}) {
  const bookmarks = sanitizeStoryProgress(progress);
  const search = query.trim().toLowerCase();
  return STORIES.filter(story => {
    const completed = bookmarks[story.id]?.completedChapters || 0;
    const finished = completed === story.chapters.length;
    const inProgress = Boolean(drafts[story.id] || bookmarks[story.id]?.replayChapter !== undefined || (completed > 0 && !finished));
    return (!search || `${story.title} ${story.subtitle} ${story.category} ${story.collection} ${story.chapters.map(chapter => chapter.text).join(' ')}`.toLowerCase().includes(search))
      && (!genre || story.genre === genre)
      && (!difficulty || story.difficulty === difficulty)
      && (!length || (length === 'short' ? story.wordCount <= 300 : story.wordCount > 300))
      && (!completion || (completion === 'finished' ? finished : completion === 'in-progress' ? inProgress : completion === 'unstarted' ? !finished && !inProgress : !finished));
  });
}

const bounded = (value, maximum) => typeof value === 'number' && Number.isFinite(value) ? Math.max(0, Math.min(value, maximum)) : 0;
const safeDate = value => typeof value === 'string' && Number.isFinite(Date.parse(value)) ? new Date(value).toISOString() : '';

export function sanitizeStoryProgress(value) {
  if (!value || typeof value !== 'object' || Array.isArray(value)) return {};
  const progress = {};
  for (const story of STORIES) {
    const record = Object.hasOwn(value, story.id) ? value[story.id] : null;
    if (!record || typeof record !== 'object' || Array.isArray(record)) continue;
    progress[story.id] = {
      completedChapters: Math.floor(bounded(record.completedChapters, story.chapters.length)),
      bestAccuracy: bounded(record.bestAccuracy, 100),
      attempts: Math.floor(bounded(record.attempts, 1000000)),
      lastPracticed: safeDate(record.lastPracticed),
    };
    if (progress[story.id].completedChapters === story.chapters.length
      && Number.isInteger(record.replayChapter) && record.replayChapter > 0 && record.replayChapter < story.chapters.length) {
      progress[story.id].replayChapter = record.replayChapter;
    }
    if (story.choice && progress[story.id].completedChapters > story.choice.chapterIndex
      && record.route !== undefined && storyRoute(story, record.route)) progress[story.id].route = record.route;
  }
  return progress;
}

export function applyStoryResult(progress, result) {
  const next = sanitizeStoryProgress(progress);
  const story = STORIES.find(item => item.id === result?.storyId);
  if (result?.mode !== 'story' || !story || !Number.isInteger(result.chapterIndex) || result.chapterIndex < 0 || result.chapterIndex >= story.chapters.length) return next;
  if (result.route !== undefined && (!storyRoute(story, result.route) || result.chapterIndex < story.choice.chapterIndex)) return next;
  const previous = next[story.id] || { completedChapters: 0, bestAccuracy: 0, attempts: 0, lastPracticed: '' };
  // Only consecutive chapters advance the bookmark. Replays keep existing credit.
  if (result.chapterIndex > previous.completedChapters) return next;
  next[story.id] = {
    completedChapters: Math.max(previous.completedChapters, result.chapterIndex + 1),
    bestAccuracy: Math.max(previous.bestAccuracy, bounded(result.accuracy, 100)),
    attempts: Math.min(1000000, previous.attempts + 1),
    lastPracticed: safeDate(result.date) || previous.lastPracticed,
    ...(story.choice && result.chapterIndex >= story.choice.chapterIndex ? { route: storyRoute(story, result.route) } : {}),
    ...(previous.completedChapters === story.chapters.length && result.chapterIndex < story.chapters.length - 1
      ? { replayChapter: result.chapterIndex + 1 } : {}),
  };
  return next;
}
