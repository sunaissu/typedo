import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

export const OFFLINE_CACHE_PREFIX = 'typedo-offline-';
export const OFFLINE_PUBLIC_FILES = ['favicon.svg', 'app-icon.svg', 'manifest.webmanifest'];

export function offlineAssetList(bundle, base = '/') {
  const prefix = base.endsWith('/') ? base : `${base}/`;
  return [...new Set(['index.html', ...Object.keys(bundle).filter(file => !file.endsWith('.map') && file !== 'sw.js'), ...OFFLINE_PUBLIC_FILES])]
    .sort().map(file => `${prefix}${file}`);
}

export function createWorkerSource({ assets, version, base = '/' }) {
  return `/* Generated by Typedo's production build. Only public app files are cached. */
const CACHE_PREFIX = ${JSON.stringify(OFFLINE_CACHE_PREFIX)};
const CACHE_NAME = CACHE_PREFIX + ${JSON.stringify(version)};
const ASSETS = ${JSON.stringify(assets)};
const BASE = ${JSON.stringify(base)};
const HOME = BASE + 'index.html';
const absolute = path => new URL(path, self.location.origin).href;
const paths = new Set(ASSETS.map(path => new URL(path, self.location.origin).pathname));

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    try {
      await cache.addAll(ASSETS.map(path => new Request(absolute(path), { cache: 'reload', credentials: 'omit' })));
    } catch (error) {
      await caches.delete(CACHE_NAME);
      throw error;
    }
  })());
});

// Keep previous bundles available for tabs still running an older version.
// No automatic activation, client takeover, reload, or deletion of saved work.
self.addEventListener('activate', event => {
  event.waitUntil(Promise.resolve());
});

self.addEventListener('message', event => {
  const reply = message => event.ports?.[0]?.postMessage(message);
  if (event.data?.type === 'OFFLINE_STATUS') {
    event.waitUntil((async () => {
      const cache = await caches.open(CACHE_NAME);
      const ready = (await Promise.all(ASSETS.map(path => cache.match(absolute(path))))).every(Boolean);
      reply({ ready, version: ${JSON.stringify(version)}, assetCount: ASSETS.length });
    })());
  }
  if (event.data?.type === 'ACTIVATE_UPDATE') {
    event.waitUntil((async () => {
      const windows = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
      const appWindows = windows.filter(client => new URL(client.url).origin === self.location.origin && new URL(client.url).pathname.startsWith(BASE));
      if (appWindows.length > 1) { reply({ activated: false, reason: 'other-tabs' }); return; }
      reply({ activated: true });
      await self.skipWaiting();
    })());
  }
});

self.addEventListener('fetch', event => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin || request.headers.has('authorization')) return;
  const appNavigation = request.mode === 'navigate' && (url.pathname === BASE || url.pathname === HOME);
  const bundledAsset = url.pathname.startsWith(BASE + 'assets/');
  if (!appNavigation && !paths.has(url.pathname) && !bundledAsset) return;
  event.respondWith((async () => {
    const key = absolute(appNavigation ? HOME : url.pathname);
    const current = await caches.open(CACHE_NAME);
    const cached = await current.match(key);
    if (cached) return cached;
    // An already open tab may request its earlier hashed chunks after an update.
    if (bundledAsset) {
      for (const name of await caches.keys()) {
        if (!name.startsWith(CACHE_PREFIX) || name === CACHE_NAME) continue;
        const previous = await (await caches.open(name)).match(key);
        if (previous) return previous;
      }
    }
    return fetch(request);
  })());
});
`;
}

export function offlinePlugin() {
  let config;
  return {
    name: 'typedo-offline', apply: 'build', enforce: 'post',
    configResolved(value) { config = value; },
    generateBundle(_options, bundle) {
      const base = config.base.startsWith('/') ? config.base : '/';
      const assets = offlineAssetList(bundle, base);
      const digest = createHash('sha256');
      for (const [name, output] of Object.entries(bundle).sort(([a], [b]) => a.localeCompare(b))) {
        digest.update(name).update(output.type === 'chunk' ? output.code : output.source);
      }
      for (const file of OFFLINE_PUBLIC_FILES) digest.update(readFileSync(resolve(config.publicDir, file)));
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: createWorkerSource({ assets, version: digest.digest('hex').slice(0, 16), base }) });
    },
  };
}
