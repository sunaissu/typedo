import { test, expect } from '@playwright/test';
test('customize below the passage, validate targets, and retain independent options', async ({page})=>{
 await page.goto('/');
 await page.getByRole('navigation',{name:'Main navigation'}).getByRole('button',{name:'Type',exact:true}).click();
 const setup=page.locator('.session-setup');const card=page.locator('.typing-card');
 expect((await setup.boundingBox()).y).toBeGreaterThan((await card.boundingBox()).y);
 await expect(setup).not.toHaveAttribute('open','');
 await page.getByText('Customize test',{exact:true}).click();
 await page.getByLabel('Duration',{exact:true}).selectOption('custom');
 await page.getByLabel('Custom seconds',{exact:true}).fill('0');await page.getByRole('button',{name:'Apply',exact:true}).click();
 await expect(page.getByRole('alert')).toContainText('15');
 await page.getByLabel('Custom seconds',{exact:true}).fill('75');await page.getByRole('button',{name:'Apply',exact:true}).click();
 await page.getByLabel('Capitalization',{exact:true}).check();
 await expect(page.getByLabel('Punctuation',{exact:true})).not.toBeChecked();
 await page.getByLabel('Symbols',{exact:true}).check();
 await expect(page.locator('.setup-heading')).toContainText('75 seconds');
 await expect(page.locator('.sidebar-local')).toHaveText('Saved in this browser');
 await page.reload();await page.getByRole('navigation',{name:'Main navigation'}).getByRole('button',{name:'Type',exact:true}).click();
 await expect(page.locator('.setup-heading')).toContainText('75 seconds');
 await page.getByText('Customize test',{exact:true}).click();
 await expect(page.getByLabel('Capitalization',{exact:true})).toBeChecked();
 await expect(page.getByLabel('Symbols',{exact:true})).toBeChecked();
 await page.getByLabel('Test format',{exact:true}).selectOption('words');
 await page.getByLabel('Word target',{exact:true}).selectOption('custom');
 await page.getByLabel('Custom words',{exact:true}).fill('123');await page.getByRole('button',{name:'Apply',exact:true}).click();
 await expect(page.locator('.setup-heading')).toContainText('123 words');
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:'output/customization-mobile.png',fullPage:true});
 await page.setViewportSize({width:1280,height:900});
 await page.screenshot({path:'output/customization-desktop.png',fullPage:true});
});
